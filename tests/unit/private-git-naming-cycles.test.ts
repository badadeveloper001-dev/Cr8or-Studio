const execute = promisify(execFile);
const repositoryKey = "badadeveloper001-dev/cr8or-studio";
const registration = { projectId: "synthetic-cycle-project", workspace: {
  id: "synthetic-registration", runtimeType: "cloud" as const, provider: "daytona", providerWorkspaceId: "synthetic-daytona",
  repositoryUrl: `https://github.com/${repositoryKey}.git`, branch: "main",
} };
type State = { head: string; index: string; title?: string };
type RemoteCommit = { sha: string; commit: { message: string } };
type Pull = { number: number; title: string; draft: boolean; state: string;
  head: { ref: string; sha: string; repo: { full_name: string } };
  base: { ref: string; sha: string; repo: { full_name: string } } };
let root: string;
let repo: string;
let initialHead: string;
let local: ReturnType<typeof createControlledDaytonaSessionAdapter>;

async function git(...args: string[]) {
  return (await execute("git", args, { cwd: repo, env: { NODE_ENV: "test", PATH: process.env.PATH, HOME: root,
    GIT_CONFIG_NOSYSTEM: "1", GIT_CONFIG_GLOBAL: "/dev/null", GIT_AUTHOR_NAME: "Synthetic owner",
    GIT_AUTHOR_EMAIL: "test@example.invalid", GIT_COMMITTER_NAME: "Synthetic owner", GIT_COMMITTER_EMAIL: "test@example.invalid" } })).stdout.trim();
}
async function localOperation(value: unknown) {
  const request = parseGitOperation(value);
  const result = await privateGitSession(local, request, buildGitOperationScope(registration, request), async () => undefined, new AbortController().signal);
  expect(result.status).toBe("SUCCEEDED");
  return result.data as State;
}
async function commitCycle(contents: string, category = "Code improvements") {
  await fs.writeFile(path.join(repo, "README.md"), contents);
  const before = await localOperation({ operation: "branch" });
  const staged = await localOperation({ operation: "stage", branch: "main", paths: ["README.md"],
    expectedHead: before.head, expectedIndex: before.index });
  return localOperation({ operation: "commit", branch: "main", expectedHead: staged.head, expectedIndex: staged.index, category });
}

/** Only immutable objects generated by the real helper enter this remote fixture.
 * Copying these snapshots simulates the separately approved upload boundary; no
 * network, git push, Daytona credential or production repository is involved. */
async function snapshotRemote() {
  const refs = (await git("for-each-ref", "--format=%(refname:short) %(objectname)", "refs/heads")).split("\n")
    .map(line => { const [name, sha] = line.split(" "); return { name, commit: { sha } }; });
  const histories = new Map<string, RemoteCommit[]>();
  for (const ref of refs) {
    const commits: RemoteCommit[] = [];
    for (const sha of (await git("rev-list", ref.commit.sha)).split("\n")) {
      commits.push({ sha, commit: { message: await git("show", "-s", "--format=%B", sha) } });
    }
    histories.set(ref.commit.sha, commits);
  }
  return { refs, histories };
}

function githubFixture(snapshot: Awaited<ReturnType<typeof snapshotRemote>>) {
  let current = snapshot;
  const pulls: Pull[] = [];
  let corruptDraft = false;
  const fetcher = vi.fn<typeof fetch>(async (url, init) => {
    const target = new URL(String(url));
    const prefix = `/repos/${repositoryKey}`;
    if (target.origin !== "https://api.github.com" || !target.pathname.startsWith(`${prefix}/`)) {
      throw new Error("Fixture must not contact another repository.");
    }
    const suffix = target.pathname.slice(prefix.length);
    const method = init?.method ?? "GET";
    let body: unknown;
    if (method === "GET" && suffix.startsWith("/git/ref/heads/")) {
      const name = decodeURIComponent(suffix.slice("/git/ref/heads/".length));
      const ref = current.refs.find(item => item.name === name);
      if (!ref) throw new Error("Missing fixture branch.");
      body = { ref: `refs/heads/${name}`, object: { type: "commit", sha: ref.commit.sha } };
    } else if (method === "GET" && suffix === "/branches") body = current.refs;
    else if (method === "GET" && suffix === "/tags") body = [];
    else if (method === "GET" && suffix === "/commits") {
      body = current.histories.get(target.searchParams.get("sha")!);
      if (!body) throw new Error("Missing immutable fixture history.");
    } else if (method === "GET" && suffix === "/pulls") body = pulls;
    else if (method === "POST" && suffix === "/pulls") {
      const request = JSON.parse(String(init?.body)) as { title: string; head: string; base: string; draft: boolean };
      // GitHub does not create a second open PR for the same head/base pair.
      if (pulls.some(pull => pull.state === "open" && pull.head.ref === request.head && pull.base.ref === request.base)) {
        return new Response(JSON.stringify({ message: "A pull request already exists." }),
          { status: 422, headers: { "content-type": "application/json" } });
      }
      const head = current.refs.find(item => item.name === request.head)!;
      const base = current.refs.find(item => item.name === request.base)!;
      const pull: Pull = { number: pulls.length + 1, title: request.title, draft: corruptDraft ? false : request.draft, state: "open",
        head: { ref: request.head, sha: head.commit.sha, repo: { full_name: repositoryKey } },
        base: { ref: request.base, sha: base.commit.sha, repo: { full_name: repositoryKey } } };
      pulls.push(pull); body = pull;
    } else if (method === "GET" && /^\/pulls\/\d+$/.test(suffix)) body = pulls.find(item => item.number === Number(suffix.split("/").at(-1)));
    else throw new Error(`Unexpected controlled GitHub request ${method} ${suffix}`);
    return new Response(JSON.stringify(body), { status: 200, headers: { "content-type": "application/json" } });
  });
  return { fetcher, pulls, update: (snapshot: typeof current) => { current = snapshot; }, nonDraft: () => { corruptDraft = true; },
    // Represents a separate owner review action, outside the application. It
    // does not invoke an adapter, merge commits, or rewrite either Git history.
    ownerClosesAfterReview: (number: number) => { pulls.find(pull => pull.number === number)!.state = "closed"; },
    mutations: () => fetcher.mock.calls.filter(([, init]) => init?.method !== "GET") };
}
function approvedPull(head: string, category = "Code improvements") {
  const request = parseGitOperation({ operation: "create-pr", branch: "main", expectedRemoteHead: head,
    baseBranch: "review", expectedBase: initialHead, category });
  const scope = buildGitOperationScope(registration, request);
  return { request, scope };
}
async function createPull(fixture: ReturnType<typeof githubFixture>, approved: ReturnType<typeof approvedPull>) {
  // This exercises the actual trusted factory and GitHub transport below their
  // release gate. PostgreSQL capability/approval enforcement has its own suite.
  return createGithubGitAdapter(() => "synthetic_test_token", fixture.fetcher).execute(
    approved.request, approved.scope, async () => undefined, new AbortController().signal);
}

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(tmpdir(), "cr8or-naming-cycles-"));
  repo = path.join(root, "repo");
  await fs.mkdir(repo);
  await git("init", "-b", "main");
  await fs.writeFile(path.join(repo, "README.md"), "Initial synthetic content\n");
  await git("add", "--", "README.md");
  await git("-c", "commit.gpgSign=false", "commit", "-m", "Initial synthetic fixture");
  initialHead = await git("rev-parse", "HEAD");
  await git("branch", "review", initialHead);
  await git("remote", "add", "origin", registration.workspace.repositoryUrl);
  local = createControlledDaytonaSessionAdapter(root);
  const owners = new Set([0, (await fs.stat("/usr/bin/git")).uid, (await fs.stat("/")).uid]);
  const program = PRIVATE_GIT_PROGRAM.replace("TRUSTED_OWNER_UIDS=(0,)", `TRUSTED_OWNER_UIDS=(${[...owners].join(",")},)`);
  const original = local.executeSessionCommand;
  local.executeSessionCommand = async (session, request, timeout) => {
    if (request.command !== `exec python3 -I -S -u -c ${shellQuote(PRIVATE_GIT_PROGRAM)}`) throw new Error("Unexpected fixture command.");
    // Only installation UID is adapted for the isolated local runner; this is
    // not evidence of live Daytona compatibility or provider isolation.
    return original(session, { ...request, command: `exec python3 -I -S -u -c ${shellQuote(program)}` }, timeout);
  };
});
afterEach(async () => {
  await local?.dispose();
  if (root) await fs.rm(root, { recursive: true, force: true });
});

describe("actual local commit and trusted remote PR naming across development cycles", () => {
  it("generates two real commits and matching monotonic draft titles without changing history", async () => {
    const first = await commitCycle("First cycle: 你好 🌍\n");
    expect(first.title).toBe("CR8OR-001: Code improvements");
    const fixture = githubFixture(await snapshotRemote());
    const firstApproval = approvedPull(first.head);
    expect(firstApproval.scope.pullRequestNaming).toEqual({ version: 2, projectCode: "CR8OR", strategy: "approved-head-commit" });
    const firstDigest = gitScopeDigest(firstApproval.scope);
    expect(await createPull(fixture, firstApproval)).toMatchObject({ status: "SUCCEEDED",
      data: { title: first.title, draft: true, number: 1 } });

    fixture.ownerClosesAfterReview(1);
    const second = await commitCycle("Second cycle: exact UTF-8 😀\n", "General maintenance");
    expect(second.title).toBe("CR8OR-002: General maintenance");
    fixture.update(await snapshotRemote());
    const secondApproval = approvedPull(second.head, "General maintenance");
    expect(await createPull(fixture, secondApproval)).toMatchObject({ status: "SUCCEEDED",
      data: { title: second.title, draft: true, number: 2 } });
    expect(fixture.pulls.map(pull => ({ number: pull.number, title: pull.title, state: pull.state }))).toEqual([
      { number: 1, title: first.title, state: "closed" }, { number: 2, title: second.title, state: "open" },
    ]);
    expect(gitScopeDigest(firstApproval.scope)).toBe(firstDigest);
    expect(await git("rev-list", "HEAD")).toBe([second.head, first.head, initialHead].join("\n"));
    expect(await git("show", "-s", "--format=%s", first.head)).toBe(first.title);
    expect(await git("show", `${first.head}:README.md`)).toBe("First cycle: 你好 🌍");
    expect(await git("show", `${initialHead}:README.md`)).toBe("Initial synthetic content");
    expect(fixture.mutations().map(([, init]) => JSON.parse(String(init?.body)))).toEqual([
      expect.objectContaining({ title: first.title, draft: true, head: "main", base: "review" }),
      expect.objectContaining({ title: second.title, draft: true, head: "main", base: "review" }),
    ]);
    expect(fixture.fetcher.mock.calls.every(([url]) => String(url).startsWith(`https://api.github.com/repos/${repositoryKey}/`))).toBe(true);
    expect(local.activeCommands.size).toBe(0);
  }, 30_000);

  it("preserves an uncertain provider refusal when the prior head/base PR is still open", async () => {
    const first = await commitCycle("First reviewed cycle\n");
    const fixture = githubFixture(await snapshotRemote());
    expect((await createPull(fixture, approvedPull(first.head))).status).toBe("SUCCEEDED");
    const second = await commitCycle("Second cycle before owner finishes first review\n");
    fixture.update(await snapshotRemote());
    expect(await createPull(fixture, approvedPull(second.head))).toMatchObject({ status: "UNKNOWN",
      cancellationConfirmed: false, cleanupConfirmed: false });
    expect(fixture.mutations()).toHaveLength(2);
    expect(fixture.pulls).toHaveLength(1);
    expect(fixture.pulls[0]).toMatchObject({ title: first.title, state: "open", draft: true });
    expect(fixture.mutations().every(([, init]) => init?.method === "POST")).toBe(true);
    expect(await git("rev-list", "HEAD")).toBe([second.head, first.head, initialHead].join("\n"));
  }, 30_000);

  it("rejects a duplicate PR identifier without recreating or modifying the first PR", async () => {
    const first = await commitCycle("First cycle\n");
    const fixture = githubFixture(await snapshotRemote());
    const approved = approvedPull(first.head);
    expect((await createPull(fixture, approved)).status).toBe("SUCCEEDED");
    expect((await createPull(fixture, approved)).status).toBe("FAILED");
    expect(fixture.mutations()).toHaveLength(1);
    expect(fixture.pulls).toHaveLength(1);
    expect(fixture.pulls[0]).toMatchObject({ title: first.title, state: "open", draft: true });
  }, 20_000);

  it("rejects a stale approval after another real commit reaches the remote instead of renumbering it", async () => {
    const first = await commitCycle("Approved contents\n");
    const approved = approvedPull(first.head);
    const digest = gitScopeDigest(approved.scope);
    const fixture = githubFixture(await snapshotRemote());
    const second = await commitCycle("External remote update simulated by immutable objects\n");
    fixture.update(await snapshotRemote());
    expect(second.title).toBe("CR8OR-002: Code improvements");
    expect((await createPull(fixture, approved)).status).toBe("FAILED");
    expect(gitScopeDigest(approved.scope)).toBe(digest);
    expect(approved.scope.expectedRemoteHead).toBe(first.head);
    expect(fixture.mutations()).toHaveLength(0);
    expect((await createPull(fixture, approvedPull(second.head))).status).toBe("SUCCEEDED");
    expect(fixture.pulls[0].title).toBe(second.title);
  }, 30_000);

  it("rejects substituted approved categories and cannot choose a different title for the same head", async () => {
    const first = await commitCycle("One approved operation\n");
    const fixture = githubFixture(await snapshotRemote());
    const approved = approvedPull(first.head);
    const changed = parseGitOperation({ ...approved.request, category: "Test improvements" });
    expect(Object.isFrozen(approved.scope.pullRequestNaming)).toBe(true);
    await expect(createGithubGitAdapter(() => "synthetic_test_token", fixture.fetcher).execute(changed,
      approved.scope, async () => undefined, new AbortController().signal)).rejects.toMatchObject({ status: 403 });
    expect(fixture.fetcher).not.toHaveBeenCalled();
    expect((await createPull(fixture, approvedPull(first.head, "Test improvements"))).status).toBe("FAILED");
    expect(fixture.mutations()).toHaveLength(0);
  }, 20_000);

  it("keeps a non-draft creation outcome UNKNOWN without any automatic corrective mutation", async () => {
    const first = await commitCycle("Draft invariant\n");
    const fixture = githubFixture(await snapshotRemote());
    fixture.nonDraft();
    expect(await createPull(fixture, approvedPull(first.head))).toMatchObject({ status: "UNKNOWN",
      cancellationConfirmed: false, cleanupConfirmed: false });
    expect(fixture.mutations()).toHaveLength(1);
    expect(fixture.pulls).toHaveLength(1);
    expect(fixture.pulls[0]).toMatchObject({ draft: false, state: "open", title: first.title });
  }, 20_000);

  it.each([{ projectCode: "OTHER" }, { sequence: 99 }, { title: "OTHER-099: Arbitrary" }])(
    "rejects client naming metadata %j before local or remote execution", fields => {
      expect(() => parseGitOperation({ operation: "commit", branch: "main", expectedHead: initialHead,
        expectedIndex: "a".repeat(64), category: "Code improvements", ...fields })).toThrow();
      expect(() => parseGitOperation({ ...approvedPull(initialHead).request, ...fields })).toThrow();
      expect(local.calls.commands).toHaveLength(0);
    });

  it("cannot borrow the trusted project code for an unrelated repository", () => {
    const unrelated = { ...registration, workspace: { ...registration.workspace, repositoryUrl: "https://github.com/unrelated/project.git" } };
    const commit = parseGitOperation({ operation: "commit", branch: "main", expectedHead: initialHead,
      expectedIndex: "a".repeat(64), category: "Code improvements" });
    expect(() => buildGitOperationScope(unrelated, commit)).toThrow();
    expect(() => buildGitOperationScope(unrelated, approvedPull(initialHead).request)).toThrow();
    expect(local.calls.commands).toHaveLength(0);
  });

  it("preserves all private Git, command and cloud-write release restrictions", () => {
    for (const gate of [assertPrivateGitAvailable, assertPrivateCloudCommandAvailable, assertPrivateCloudWriteTransportAvailable]) {
      expect(gate).toThrow(expect.objectContaining({ status: 503 }));
    }
    expect(local.calls.commands).toHaveLength(0);
  });
});
